export const WORDS_LIST=Object.freeze(Object.entries(GROUPS).flatMap(([question,words])=>words.split(' ').map(answer=>Object.freeze({question,answer}))));
export const WORDS_PER_GAME=64;
export function wordsItems(random=Math.random){const pool=[...WORDS_LIST];for(let i=pool.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[pool[i],pool[j]]=[pool[j],pool[i]];}return pool.slice(0,WORDS_PER_GAME).map(p=>({...p}));}
